/**
 * Metadatos en imágenes: detectarlos y quitarlos. Sin dependencias. Lo usan `scripts/marca.mjs` (para
 * limpiar lo que se versiona) y `security-tests/privacidad-repo.test.ts` (para comprobar que ninguna
 * imagen versionada los tenga).
 *
 * Una imagen puede traer datos del equipo o de quien la hizo: EXIF, XMP, comentarios, el software de
 * origen, credenciales de contenido (C2PA), rutas. La regla es estricta: en un PNG solo quedan los chunks
 * de la imagen; en un SVG, nada de metadatos, comentarios ni espacios de nombres de editores.
 */

const FIRMA_PNG = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);

/** Los chunks que forman la imagen. Cualquier otro (tEXt, iTXt, eXIf, caBX, tIME, iCCP…) es metadato. */
const CHUNKS_DE_IMAGEN = new Set(['IHDR', 'PLTE', 'IDAT', 'IEND', 'tRNS']);

export const esPng = (datos) => datos.subarray(0, 8).equals(FIRMA_PNG);

function chunksPng(datos) {
  const chunks = [];
  let o = 8;
  while (o + 12 <= datos.length) {
    const largo = datos.readUInt32BE(o);
    const tipo = datos.toString('latin1', o + 4, o + 8);
    chunks.push({ tipo, inicio: o, fin: o + 12 + largo });
    o += 12 + largo;
    if (tipo === 'IEND') break;
  }
  return chunks;
}

/** Un PNG solo con los chunks de la imagen. */
export function limpiarPng(datos) {
  if (!esPng(datos)) throw new Error('No es un PNG');
  const partes = [FIRMA_PNG];
  for (const chunk of chunksPng(datos)) {
    if (CHUNKS_DE_IMAGEN.has(chunk.tipo)) partes.push(datos.subarray(chunk.inicio, chunk.fin));
  }
  return Buffer.concat(partes);
}

/** Las imágenes de un ICO: cada una es un PNG o un BMP (que no admite metadatos). */
function imagenesIco(datos) {
  const cantidad = datos.readUInt16LE(4);
  const imagenes = [];
  for (let i = 0; i < cantidad; i++) {
    const entrada = 6 + i * 16;
    const largo = datos.readUInt32LE(entrada + 8);
    const inicio = datos.readUInt32LE(entrada + 12);
    imagenes.push(datos.subarray(inicio, inicio + largo));
  }
  return imagenes;
}

const PATRONES_SVG = [
  ['metadata', /<metadata[\s>]/i],
  ['comentario', /<!--/],
  ['RDF', /<rdf:|xmlns:rdf=/i],
  ['Dublin Core', /<dc:|xmlns:dc=/i],
  ['XMP', /xmlns:xmp|<x:xmpmeta|xpacket/i],
  ['C2PA', /c2pa/i],
  ['Inkscape', /inkscape[:\s]/i],
  ['Sodipodi', /sodipodi[:\s]/i],
  ['Illustrator', /xmlns:(?:i|x|graph)=|adobe/i],
  ['Sketch', /sketch:|xmlns:sketch/i],
  ['Figma', /figma/i],
  ['generador', /generator|generated by|created with/i],
];

/**
 * Qué metadatos tiene una imagen, por nombre (sin el contenido). Vacío si no tiene. Un formato que no
 * se sabe revisar falla cerrado.
 */
export function metadatosDe(datos, extension) {
  const ext = extension.toLowerCase().replace(/^\./, '');
  if (ext === 'svg') {
    const texto = datos.toString('utf8');
    return PATRONES_SVG.filter(([, patron]) => patron.test(texto)).map(([nombre]) => nombre);
  }
  if (ext === 'png') {
    if (!esPng(datos)) return ['no es un PNG'];
    return chunksPng(datos)
      .map((c) => c.tipo)
      .filter((tipo) => !CHUNKS_DE_IMAGEN.has(tipo))
      .map((tipo) => `chunk ${tipo}`);
  }
  if (ext === 'ico') {
    if (datos.readUInt16LE(0) !== 0 || datos.readUInt16LE(2) !== 1) return ['no es un ICO'];
    return imagenesIco(datos).flatMap((imagen, i) =>
      esPng(imagen) ? metadatosDe(imagen, 'png').map((m) => `imagen ${i}: ${m}`) : [],
    );
  }
  return [`formato .${ext} sin revisar: agregarlo a scripts/metadatos-imagenes.mjs`];
}

/** Extensiones de imagen que el test revisa. */
export const EXTENSIONES_DE_IMAGEN = /\.(png|jpe?g|gif|webp|avif|bmp|tiff?|ico|icns|svg|heic)$/i;

/** Un SVG sin metadatos, comentarios ni espacios de nombres que no sean de SVG. */
export function limpiarSvg(texto) {
  return texto
    .replace(/<metadata[\s\S]*?<\/metadata>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+xmlns:(?!xlink=)[\w-]+="[^"]*"/g, '')
    .replace(/\s+[\w-]+:[\w-]+="[^"]*"/g, (atributo) =>
      /^\s+xlink:/.test(atributo) ? atributo : '',
    );
}
